"""An 18-Toffoli consuming GF64 inverse with seventeen total live wires.

The fixed schedule was generated by exhaustive truth-table affine algebra.
Each HMR character is an explicit quadratic in remaining wires plus a linear
character of the original input, which is returned to the caller.
"""
from pathlib import Path
import sys,json
HERE=Path(__file__).resolve().parent
sys.path.insert(0,str(HERE))
from jet_norm6 import replacement_ids,base,xs
from exp.jet24 import pro_jet as jet
from exp.inverse_search import inverse20 as ref
from exp.noscratch import schedules
from exp.arithmetic import field as ar
PLAN=json.loads((HERE/'consuming_plan.json').read_text())


def change_basis(b,live,rows):
    """Apply an invertible affine map, with rows in constant-first format."""
    n=len(live)
    columns=[sum(((r>>(j+1))&1)<<i for i,r in enumerate(rows)) for j in range(n)]
    ar.linear_inplace(b,live,columns)
    for q,r in zip(live,rows):
        if r&1:b.x(q)


def retire(b,live,pool,transcript,record):
    change_basis(b,live,record['rows'])
    for action in record['retire']:
        p=action['index']
        for j in action['mix']:b.cx(live[j],live[p])
        q=live.pop(p)
        m=b.alloc_bits(1)[0];b.hmr(q,m)
        for term in action['phase']:
            if term[0]=='constant':b.z(m)
            elif term[0]=='linear':b.cz(live[term[1]],m)
            elif term[0]=='pair':b.ccz(live[term[1]],live[term[2]],m)
            else:b.cx(m,transcript[term[1]])
        b.free(m);pool.append(q)


def inverse6_consume17(b,x):
    """x <- inverse0(x); return the exact original-x linear phase mask."""
    assert len(x)==6
    ar.linear_inplace(b,x,jet.TO6)
    raw=b.alloc_qubits(6)
    for j,(left,right) in enumerate(jet.RAW):
        with ref.expose_pair(b,x,left,right) as (p,q):b.init_and(p,q,raw[j])
    w=ref.inverse3_virtual(b,list(x)+list(raw),ref.norm_forms(1))
    pool=list(b.alloc_qubits(2))
    all_wires=list(x)+list(raw)+list(w)+pool[:]
    live=list(x)+list(raw)+list(w)
    transcript=b.alloc_bits(6);b.bit_store(transcript,False)
    for step in PLAN['steps']:
        out=pool.pop()
        with ref.expose_pair(b,live,step['left'],step['right']) as (p,q):b.init_and(p,q,out)
        live.append(out)
        retire(b,live,pool,transcript,step)
    retire(b,live,pool,transcript,PLAN['final'])
    assert len(live)==6
    for i,target in enumerate(x):
        source=live[i]
        if str(source)==str(target):continue
        other=next((j for j,q in enumerate(live) if str(q)==str(target)),None)
        b.swap(source,target)
        live[i]=target
        if other is not None:live[other]=source
    retained=set(map(str,x))
    b.free([q for q in all_wires if str(q) not in retained])
    return transcript


def inverse_stream_narrow(b,x):
    live=b.num_allocated_qubits
    if len(x)==6 and live+12>889 and live+11<=889:
        return inverse6_consume17(b,x)
    return fallback(b,x)

fallback=xs.clone(schedules.inverse_stream_noscratch,dict(schedules.inverse_stream_noscratch.__globals__,inverse_stream_noscratch=inverse_stream_narrow))
decode=xs.private_rebind(base.decode,replacement_ids(base.decode,schedules.inverse_stream_noscratch,inverse_stream_narrow))
